"""
plot_results.py

Post-processing script for the Navier--Stokes POD-Galerkin vs PODNN project.
It reads the CSV files already generated by the project and creates report-ready
figures without rerunning the expensive simulations.

Run from the project root, for example:
    python3 plot_results.py

Optional:
    python3 plot_results.py --root /shared
    python3 plot_results.py --output Results/Comparison_Plots

Expected input files, if run from the project root:
    Results/POD_Galerkin/fom_vs_pod_galerkin_metrics.csv
    Results/POD_Galerkin/fom_vs_pod_galerkin_summary.csv
    Results/PODNN/fom_vs_podnn_metrics.csv
    Results/PODNN/fom_vs_podnn_summary.csv

The script is intentionally independent from the FEM/POD code: it only needs
pandas, numpy and matplotlib.
"""

from __future__ import annotations

import argparse
import pickle
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


ERROR_COLUMNS = ["err_U", "err_u_x", "err_u_y", "err_u_mag", "err_p"]
ERROR_LABELS = {
    "err_U": "Global solution",
    "err_u_x": "u_x",
    "err_u_y": "u_y",
    "err_u_mag": "|u|",
    "err_p": "p",
}

METHOD_SPECS = {
    "POD-Galerkin": {
        "folder_candidates": ["POD_Galerkin", "PODGalerkin", "POD-Galerkin"],
        "metrics_candidates": [
            "fom_vs_pod_galerkin_metrics.csv",
            "fom_vs_pod_metrics.csv",
            "metrics.csv",
        ],
        "summary_candidates": [
            "fom_vs_pod_galerkin_summary.csv",
            "fom_vs_pod_summary.csv",
            "summary.csv",
        ],
    },
    "PODNN": {
        "folder_candidates": ["PODNN", "POD_NN"],
        "metrics_candidates": [
            "fom_vs_podnn_metrics.csv",
            "fom_vs_pod_nn_metrics.csv",
            "metrics.csv",
        ],
        "summary_candidates": [
            "fom_vs_podnn_summary.csv",
            "fom_vs_pod_nn_summary.csv",
            "summary.csv",
        ],
    },
     "PINN": {
        "folder_candidates": [
            "PINN"
        ],
        "metrics_candidates": [
            "fom_vs_pinn_metrics.csv",
            "metrics.csv",
        ],
        "summary_candidates": [
            "fom_vs_pinn_summary.csv",
            "summary.csv",
        ],
     },
}


def find_first_existing(paths: List[Path]) -> Optional[Path]:
    for path in paths:
        if path.exists():
            return path
    return None


def find_method_files(root: Path, method: str) -> Tuple[Optional[Path], Optional[Path]]:
    spec = METHOD_SPECS[method]
    search_roots = [root / "Results", root]

    metric_paths: List[Path] = []
    summary_paths: List[Path] = []

    for base in search_roots:
        for folder in spec["folder_candidates"]:
            for name in spec["metrics_candidates"]:
                metric_paths.append(base / folder / name)
            for name in spec["summary_candidates"]:
                summary_paths.append(base / folder / name)

    # Fallback: recursive search, useful if the folder names are slightly different.
    for name in spec["metrics_candidates"]:
        metric_paths.extend(root.rglob(name))
    for name in spec["summary_candidates"]:
        summary_paths.extend(root.rglob(name))

    return find_first_existing(metric_paths), find_first_existing(summary_paths)


def load_results(root: Path) -> Dict[str, Dict[str, pd.DataFrame | Path]]:
    results: Dict[str, Dict[str, pd.DataFrame | Path]] = {}

    for method in METHOD_SPECS:
        metrics_path, summary_path = find_method_files(root, method)

        if metrics_path is None:
            print(f"[Warning] Metrics file not found for {method}. Skipping this method.")
            continue

        metrics = pd.read_csv(metrics_path)
        summary = pd.read_csv(summary_path) if summary_path is not None else build_summary(metrics)

        results[method] = {
            "metrics": metrics,
            "summary": summary,
            "metrics_path": metrics_path,
        }

        print(f"[Loaded] {method} metrics: {metrics_path}")
        if summary_path is not None:
            print(f"[Loaded] {method} summary: {summary_path}")
        else:
            print(f"[Info] No summary found for {method}; computed summary from metrics.")

    if not results:
        raise FileNotFoundError(
            "No POD-Galerkin or PODNN metrics were found. Run this script from the project root, "
            "or pass --root /path/to/project."
        )

    return results


def build_summary(metrics: pd.DataFrame) -> pd.DataFrame:
    rows = []
    numeric_cols = [col for col in metrics.columns if pd.api.types.is_numeric_dtype(metrics[col])]
    for col in numeric_cols:
        values = metrics[col].replace([np.inf, -np.inf], np.nan).dropna()
        if len(values) == 0:
            continue
        rows.append({
            "metric": col,
            "mean": values.mean(),
            "max": values.max(),
            "min": values.min(),
            "std": values.std(ddof=0),
        })
    return pd.DataFrame(rows)


def summary_value(summary: pd.DataFrame, metric: str, stat: str) -> float:
    row = summary.loc[summary["metric"] == metric]
    if row.empty or stat not in summary.columns:
        return np.nan
    return float(row.iloc[0][stat])


def set_common_style() -> None:
    plt.rcParams.update({
        "figure.figsize": (8, 5),
        "axes.grid": True,
        "grid.alpha": 0.3,
        "font.size": 11,
        "axes.titlesize": 13,
        "axes.labelsize": 11,
        "legend.fontsize": 10,
        "savefig.dpi": 300,
        "savefig.bbox": "tight",
    })


def save_current(output_dir: Path, filename: str) -> Path:
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / filename
    plt.tight_layout()
    plt.savefig(path)
    plt.close()
    print(f"[Saved] {path}")
    return path



def plot_component_mean_errors(results: Dict[str, Dict[str, pd.DataFrame | Path]], output_dir: Path) -> None:
    methods = list(results.keys())
    labels = [ERROR_LABELS[c] for c in ERROR_COLUMNS]
    x = np.arange(len(ERROR_COLUMNS))
    width = 0.8 / max(len(methods), 1)

    plt.figure(figsize=(10, 5))
    for i, method in enumerate(methods):
        summary = results[method]["summary"]
        vals = [100 * summary_value(summary, col, "mean") for col in ERROR_COLUMNS]
        offset = (i - (len(methods) - 1) / 2) * width
        plt.bar(x + offset, vals, width, label=method)

    plt.xticks(x, labels)
    plt.ylabel("Mean relative error [%]")
    plt.yscale("log")
    plt.title("Accuracy comparison: POD-Galerkin, PODNN and PINN")
    plt.legend()
    save_current(output_dir, "accuracy_comparison.png")




def plot_runtime_comparison(results, output_dir):
    method_names = list(results.keys())

    fom_times = []
    method_times = []

    for method in method_names:
        summary = results[method]["summary"]

        fom_times.append(
            summary_value(summary, "fom_time_s", "mean")
        )

        method_times.append(
            summary_value(summary, "rom_time_s", "mean")
        )

    labels = ["FOM"] + method_names
    times = [np.nanmean(fom_times)] + method_times

    plt.figure(figsize=(9, 5))
    bars = plt.bar(labels, times)

    plt.ylabel("Mean online time [s]")
    plt.yscale("log")
    plt.title("Online computational time comparison")

    for bar, value in zip(bars, times):
        plt.text(
            bar.get_x() + bar.get_width() / 2,
            value,
            f"{value:.3e}",
            ha="center",
            va="bottom",
            fontsize=9
        )

    save_current(
        output_dir,
        "computational_time_comparison_all_methods.png"
    )


def plot_speedup(results, output_dir):
    methods = list(results.keys())

    speedups = [
        summary_value(
            results[method]["summary"],
            "speedup",
            "mean"
        )
        for method in methods
    ]

    plt.figure(figsize=(8, 5))
    bars = plt.bar(methods, speedups)

    # Speedup = 1 means same computational cost as FOM
    plt.axhline(
        y=1.0,
        linestyle="--",
        linewidth=1.2,
        label="Same time as FOM"
    )

    plt.yscale("log")
    plt.ylabel("Mean speedup over FOM")
    plt.title("Online speedup comparison")

    for bar, value in zip(bars, speedups):
        plt.text(
            bar.get_x() + bar.get_width() / 2,
            value,
            f"{value:.3g}×",
            ha="center",
            va="bottom",
            fontsize=9
        )

    plt.legend()

    save_current(
        output_dir,
        "speedup_comparison_all_methods.png"
    )

def plot_compression_ratio(results, output_dir):
    pod_methods = [
        method
        for method in ["POD-Galerkin", "PODNN"]
        if method in results
    ]

    ratios = [
        summary_value(
            results[method]["summary"],
            "compression_ratio",
            "mean"
        )
        for method in pod_methods
    ]

    plt.figure(figsize=(7, 5))
    bars = plt.bar(pod_methods, ratios)

    plt.ylabel("FOM DoFs / reduced DoFs")
    plt.title("POD model compression ratio")

    for bar, value in zip(bars, ratios):
        plt.text(
            bar.get_x() + bar.get_width() / 2,
            value,
            f"{value:.1f}×",
            ha="center",
            va="bottom"
        )

    save_current(
        output_dir,
        "compression_ratio_pod_methods.png"
    )

def write_tables(results, output_dir):
    rows = []

    for method, data in results.items():
        s = data["summary"]

        rows.append({
            "Method": method,
            "Mean velocity error (%)": 100 * summary_value(s, "err_u_mag", "mean"),
            "Mean pressure error (%)": 100 * summary_value(s, "err_p", "mean"),
            "Mean FOM time (s)": summary_value(s, "fom_time_s", "mean"),
            "Mean ROM time (s)": summary_value(s, "rom_time_s", "mean"),
            "Mean speedup": summary_value(s, "speedup", "mean"),
        })

    df = pd.DataFrame(rows)

    df.to_csv(output_dir / "comparison_summary.csv", index=False)



def main() -> None:
    parser = argparse.ArgumentParser(description="Generate POD-Galerkin/PODNN result plots from saved CSV files.")
    parser.add_argument("--root", type=str, default=".", help="Project root folder. Default: current directory.")
    parser.add_argument("--output", type=str, default=None, help="Output folder for plots. Default: <root>/Results/Comparison_Plots.")
    parser.add_argument("--skip-eigen", action="store_true", help="Skip optional POD eigenvalue decay plot.")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    output_dir = Path(args.output).resolve() if args.output else root / "Results" / "Comparison"
    output_dir.mkdir(parents=True, exist_ok=True)

    set_common_style()
    results = load_results(root)

    plot_component_mean_errors(results, output_dir)      # accuracy_comparison
    plot_runtime_comparison(results, output_dir)         # computational_time_comparison
    plot_speedup(results, output_dir)  
    plot_compression_ratio(results, output_dir)                  # speedup_comparison
    write_tables(results, output_dir)

    print("\nDone. Open this folder to see the generated plots:")
    print(output_dir)


if __name__ == "__main__":
    main()
